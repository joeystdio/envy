import Foundation

/// The two files a shell sources: a fixed hook (`init.sh`) and generated variables (`vars.sh`).
///
/// The hook runs at every prompt (and on `cd` in zsh). It only does work when `state` holds a new
/// generation stamp or the shell moved into or out of a project folder. It then puts back everything
/// it set earlier and applies the current set, so disabling a variable removes it from open shells and
/// restores any value it had overridden.
///
/// Bookkeeping is exported, so child shells, tmux panes and editor terminals can undo what their parent
/// applied: `__ENVY_VARS` lists the managed names, and `__ENVY_O_<NAME>` keeps each overridden original.
public enum ShellScript {
    public static let bundleIdentifier = "dev.envy.Envy"

    public static let hook = #"""
    # Envy shell hook. Written by Envy.app; local changes are overwritten.
    # Sourced from ~/.zshrc or ~/.bashrc. Works in zsh and bash 3.2+.
    #
    #   envy status   what's loaded in this shell
    #   envy reload   reload right now
    #   envy open     open the app

    __envy_dir="${ENVY_DIR:-$HOME/.config/envy}"
    __envy_gen=""
    __envy_sig=""
    __envy_m=""
    __envy_active=""
    __ENVY_VARS="${__ENVY_VARS-}"

    __envy_match() { __envy_m=""; }
    __envy_apply() { :; }

    # __envy_set NAME VALUE: export NAME, remembering the value it had before Envy set it.
    __envy_set() {
      case " $__ENVY_VARS" in
        *" $1 "*) ;;
        *)
          if eval "[ -n \"\${$1+x}\" ]"; then
            eval "export __ENVY_O_$1=\"\${$1}\""
          fi
          __ENVY_VARS="$__ENVY_VARS$1 "
          ;;
      esac
      export "$1=$2"
    }

    # Put every variable Envy set back to its earlier value, or unset it.
    __envy_revert() {
      local __envy_l="$__ENVY_VARS" __envy_n
      while [ -n "$__envy_l" ]; do
        case "$__envy_l" in
          *" "*) __envy_n="${__envy_l%% *}"; __envy_l="${__envy_l#* }" ;;
          *) __envy_n="$__envy_l"; __envy_l="" ;;
        esac
        case "$__envy_n" in ''|[0-9]*|*[!A-Za-z0-9_]*) continue ;; esac
        if eval "[ -n \"\${__ENVY_O_$__envy_n+x}\" ]"; then
          eval "export $__envy_n=\"\${__ENVY_O_$__envy_n}\""
          unset "__ENVY_O_$__envy_n"
        else
          unset "$__envy_n"
        fi
      done
      __ENVY_VARS=""
      __envy_active=""
    }

    __envy_hook() {
      local __envy_rc=$? __envy_g=""
      if [ -r "$__envy_dir/state" ]; then
        IFS= read -r __envy_g < "$__envy_dir/state" || :
      fi
      if [ "$__envy_g" != "$__envy_gen" ]; then
        __envy_gen="$__envy_g"
        __envy_match() { __envy_m=""; }
        __envy_apply() { :; }
        if [ -r "$__envy_dir/vars.sh" ]; then . "$__envy_dir/vars.sh"; fi
      fi
      __envy_match
      if [ "$__envy_gen|$__envy_m" != "$__envy_sig" ]; then
        __envy_sig="$__envy_gen|$__envy_m"
        __envy_revert
        __envy_apply
        if [ -n "$__ENVY_VARS" ]; then export __ENVY_VARS; fi
      fi
      return $__envy_rc
    }

    # "function envy" rather than "envy()" so an existing alias named envy can't break the definition in zsh.
    function envy {
      case "${1:-status}" in
        status)
          printf 'Envy: %s\n' "${__envy_active:-nothing loaded here}"
          if [ -n "$__ENVY_VARS" ]; then printf 'Variables: %s\n' "${__ENVY_VARS% }"; fi
          ;;
        reload)
          __envy_gen="(reload)"
          __envy_sig=""
          __envy_hook
          envy status
          ;;
        open) open -b dev.envy.Envy ;;
        *) printf 'usage: envy [status|reload|open]\n' >&2; return 2 ;;
      esac
    }

    if [ -n "${ZSH_VERSION-}" ]; then
      autoload -Uz add-zsh-hook
      add-zsh-hook precmd __envy_hook
      add-zsh-hook chpwd __envy_hook
    elif [ -n "${BASH_VERSION-}" ]; then
      case ";${PROMPT_COMMAND-};" in
        *";__envy_hook;"*) ;;
        *) PROMPT_COMMAND="__envy_hook${PROMPT_COMMAND:+;$PROMPT_COMMAND}" ;;
      esac
    fi
    __envy_hook

    """#

    /// The generated `vars.sh`. Order is precedence (later wins): Global, projects loaded in every shell,
    /// then folder projects with the deepest folder last. Expanding values can reference anything set above them.
    public static func vars(for config: EnvConfig, maskSecrets: Bool = false) -> String {
        let alwaysOn = config.projects.filter { $0.isEnabled && !$0.isFolderScoped }
        let scoped = config.projects.enumerated()
            .filter { $0.element.isEnabled && $0.element.isFolderScoped && !loadable($0.element).isEmpty }
            .sorted { (depth($0.element), $0.offset) < (depth($1.element), $1.offset) }
            .map(\.element)

        var out = """
        # Generated by Envy. Do not edit; changes here are overwritten.
        # Later lines win: Global, then projects loaded in every shell, then folder projects (deepest folder last).

        __envy_match() {
          __envy_m=""

        """
        for (n, p) in scoped.enumerated() {
            out += "  case \"$PWD/\" in \(folderPatterns(p.folders).joined(separator: "|"))) __envy_m=\"$__envy_m \(n + 1)\" ;; esac\n"
        }
        out += "}\n\n__envy_apply() {\n"
        if config.global.isEnabled {
            out += block(config.global, indent: "  ", maskSecrets: maskSecrets)
        }
        for p in alwaysOn {
            out += block(p, indent: "  ", maskSecrets: maskSecrets)
        }
        for (n, p) in scoped.enumerated() {
            out += "  # \(commentSafe(p.name)), inside \(p.folders.map(commentSafe).joined(separator: ", "))\n"
            out += "  case \" $__envy_m \" in *\" \(n + 1) \"*)\n"
            out += block(p, indent: "    ", maskSecrets: maskSecrets, withComment: false)
            out += "  ;; esac\n"
        }
        out += "  :\n}\n"
        return out
    }

    /// Variables of `project` that make it into the shell.
    public static func loadable(_ project: Project) -> [EnvVar] {
        project.variables.filter { $0.isEnabled && $0.hasValidKey }
    }

    static func block(_ p: Project, indent: String, maskSecrets: Bool, withComment: Bool = true) -> String {
        let vars = loadable(p)
        guard !vars.isEmpty else { return "" }
        var s = withComment ? "\(indent)# \(commentSafe(p.name))\n" : ""
        s += "\(indent)__envy_active=\"${__envy_active:+$__envy_active, }\"\(singleQuoted(p.name))\n"
        for v in vars {
            let value = maskSecrets && v.isSecret ? singleQuoted("••••••") : shellValue(v)
            s += "\(indent)__envy_set \(v.key) \(value)\n"
        }
        return s
    }

    public static func shellValue(_ v: EnvVar) -> String {
        v.expands ? expandable(v.value) : singleQuoted(v.value)
    }

    public static func singleQuoted(_ s: String) -> String {
        "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    /// A double-quoted string the shell expands: `$VAR`, `${VAR}` and `$(cmd)` work, backticks don't,
    /// and `~` at the start or after `:` becomes `$HOME`.
    public static func expandable(_ value: String) -> String {
        var v = value
        if v == "~" {
            v = "$HOME"
        } else if v.hasPrefix("~/") {
            v = "$HOME" + v.dropFirst()
        }
        v = v.replacingOccurrences(of: ":~/", with: ":$HOME/")
        let escaped = v
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
            .replacingOccurrences(of: "`", with: "\\`")
        return "\"\(escaped)\""
    }

    /// `case` patterns matching a folder and everything below it, for the path as given and with symlinks
    /// resolved, since `$PWD` can be either (e.g. `/tmp` vs `/private/tmp`).
    static func folderPatterns(_ folders: [String]) -> [String] {
        var seen = Set<String>(), out: [String] = []
        for folder in folders {
            let expanded = (folder as NSString).expandingTildeInPath
            for path in [expanded, URL(fileURLWithPath: expanded).resolvingSymlinksInPath().path] {
                var p = path
                while p.count > 1, p.hasSuffix("/") { p.removeLast() }
                let prefix = p == "/" ? "/" : p + "/"
                if seen.insert(prefix).inserted { out.append(singleQuoted(prefix) + "*") }
            }
        }
        return out
    }

    static func depth(_ p: Project) -> Int {
        p.folders.map { ($0 as NSString).expandingTildeInPath.count }.max() ?? 0
    }

    static func commentSafe(_ s: String) -> String {
        s.replacingOccurrences(of: "\n", with: " ").replacingOccurrences(of: "\r", with: " ")
    }
}
