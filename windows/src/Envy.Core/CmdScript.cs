using System.Text;

namespace Envy.Core;

/// <summary>
/// Command Prompt support: init.cmd runs from the AutoRun registry value whenever cmd.exe starts, envy.cmd is the envy
/// command, and vars.cmd holds the generated variables. cmd has no prompt hook, so variables load once per window, for
/// the folder it starts in; "envy reload" loads them again for the current folder. Every line starts with @ rather than
/// using echo off, so the prompt's echo state is never touched.
/// </summary>
public static class CmdScript
{
    public static string Init(string shellDir) => $"""
        @rem Envy for Command Prompt. Written by Envy; local changes are overwritten.
        @rem Runs from the AutoRun value each time cmd.exe starts. Command Prompt has no prompt hook, so variables load
        @rem once per window, for the folder it starts in. After cd, run "envy reload".
        @if defined __envy_busy exit /b 0
        @set "__envy_busy=1"
        @set "__envy_dir={Escape(shellDir)}"
        @if defined ENVY_DIR set "__envy_dir=%ENVY_DIR%"
        @rem Runs a copy, since cmd rereads a batch file line by line and Envy may replace vars.cmd meanwhile. Each window
        @rem claims its own folder for it: windows that start in the same second draw the same %RANDOM% numbers.
        @set "__envy_try=0"
        :envy_claim
        @set /a "__envy_try+=1"
        @set "__envy_run=%__envy_dir%\run-%RANDOM%%RANDOM%"
        @mkdir "%__envy_run%" >nul 2>&1 && goto envy_claimed
        @if %__envy_try% lss 20 goto envy_claim
        @call "%__envy_dir%\vars.cmd"
        @goto envy_ran
        :envy_claimed
        @copy /y "%__envy_dir%\vars.cmd" "%__envy_run%\vars.cmd" >nul 2>&1 && call "%__envy_run%\vars.cmd"
        @rmdir /s /q "%__envy_run%" >nul 2>&1
        :envy_ran
        @set "__envy_run=" & set "__envy_try="
        @if /i "%~1"=="reload" goto envy_done
        @rem The envy command, for windows you type in (not for cmd /c).
        @set "__envy_cl=%CMDCMDLINE:"=%"
        @if "%__envy_cl: /c=%"=="%__envy_cl%" doskey envy="%__envy_dir%\envy.cmd" $*
        @set "__envy_cl="
        :envy_done
        @set "__envy_busy="

        """.ReplaceLineEndings("\r\n");

    public static string EnvyCommand(string? appPath) => $"""
        @rem The envy command for Command Prompt. Written by Envy; local changes are overwritten.
        @rem   envy status   what's loaded in this window
        @rem   envy reload   load again for the current folder
        @rem   envy open     open the app
        @if "%~1"=="" goto envy_status
        @if /i "%~1"=="status" goto envy_status
        @if /i "%~1"=="reload" goto envy_reload
        @if /i "%~1"=="open" goto envy_open
        @echo usage: envy [status^|reload^|open] 1>&2
        @exit /b 2
        :envy_status
        @setlocal EnableDelayedExpansion
        @if defined __envy_active (echo(Envy: !__envy_active!) else echo(Envy: nothing loaded here
        @if defined __ENVY_VARS echo(Variables: !__ENVY_VARS:~0,-1!
        @endlocal
        @exit /b 0
        :envy_reload
        @call "%~dp0init.cmd" reload
        @goto envy_status
        :envy_open
        {(appPath is null ? "@echo Envy is not installed here. 1>&2" : $"@start \"\" \"{Escape(appPath)}\"")}
        @exit /b 0

        """.ReplaceLineEndings("\r\n");

    /// <summary>The generated vars.cmd. Same order as the other shells; folder projects match the folder cmd starts in.</summary>
    public static string Vars(EnvConfig config, string? home = null, bool maskSecrets = false)
    {
        var (alwaysOn, scoped) = Scopes.Ordered(config, home);
        var s = new StringBuilder();
        var label = 0;
        s.Append("""
            @rem Generated by Envy. Do not edit; changes here are overwritten.
            @rem Later lines win: Global, then projects loaded in every window, then folder projects (deepest folder last).
            @rem Puts back what Envy set before, for example in the shell this window was started from.
            @if not defined __ENVY_VARS goto envy_reverted
            @for %%n in (%__ENVY_VARS%) do @if defined __ENVY_O_%%n (call set "%%n=%%__ENVY_O_%%n%%" & set "__ENVY_O_%%n=") else set "%%n="
            @set "__ENVY_VARS="
            :envy_reverted
            @set "__envy_active="

            """);
        if (scoped.Count > 0)
        {
            s.Append("@set \"__envy_m= \"\n@set \"__envy_cd=%CD%\"\n@if not \"%__envy_cd:~-1%\"==\"\\\" set \"__envy_cd=%__envy_cd%\\\"\n");
            for (var n = 0; n < scoped.Count; n++)
            {
                var prefixes = scoped[n].Folders.SelectMany(f => PathStyle.Variants(f, home))
                    .Select(v => PathStyle.AsPrefix(PathStyle.FromPosix(v)))
                    .Distinct(StringComparer.OrdinalIgnoreCase);
                foreach (var prefix in prefixes)
                    s.Append($"@if /i \"%__envy_cd:~0,{prefix.Length}%\"==\"{Escape(prefix)}\" set \"__envy_m=%__envy_m%{n + 1} \"\n");
            }
        }
        foreach (var p in alwaysOn) s.Append(Block(p, ref label, maskSecrets));
        for (var n = 0; n < scoped.Count; n++)
        {
            var end = $"envy_p{n + 1}";
            s.Append($"@rem {Comment(scoped[n].Name)}, inside {Comment(string.Join(", ", scoped[n].Folders))}\n");
            s.Append($"@if \"%__envy_m: {n + 1} =%\"==\"%__envy_m%\" goto {end}\n");
            s.Append(Block(scoped[n], ref label, maskSecrets));
            s.Append($":{end}\n");
        }
        s.Append("@if defined __envy_active set \"__envy_active=%__envy_active:~2%\"\n");
        s.Append("@set \"__envy_l=\" & set \"__envy_m=\" & set \"__envy_cd=\"\n");

        var text = s.ToString();
        // cmd reads batch files in the console's code page; switch to UTF-8 only when a value needs it.
        if (text.Any(c => c > 127))
        {
            text = "@for /f \"tokens=2 delims=:.\" %%c in ('chcp') do @set \"__envy_cp=%%c\"\n@chcp 65001 >nul\n"
                + text + "@chcp %__envy_cp% >nul\n@set \"__envy_cp=\"\n";
        }
        return text.ReplaceLineEndings("\r\n");
    }

    static string Block(Project p, ref int label, bool maskSecrets)
    {
        var vars = Scopes.Loadable(p);
        if (vars.Count == 0) return "";
        var s = new StringBuilder();
        s.Append($"@rem {Comment(p.Name)}\n");
        s.Append($"@set \"__envy_active=%__envy_active%, {Escape(p.Name.Replace("\"", ""))}\"\n");
        foreach (var v in vars)
        {
            if (SetLine(maskSecrets && v.IsSecret ? v with { Value = "******", Expands = false } : v) is not { } line)
            {
                s.Append($"@rem {v.Key} is skipped: Command Prompt can't hold this value (more than one line, or a quote in an expanding value).\n");
                continue;
            }
            label++;
            s.Append($"@set \"__envy_l= %__ENVY_VARS%\"\n");
            s.Append($"@if not \"%__envy_l: {v.Key} =%\"==\"%__envy_l%\" goto envy_v{label}\n");
            s.Append($"@if defined {v.Key} set \"__ENVY_O_{v.Key}=%{v.Key}%\"\n");
            s.Append($"@set \"__ENVY_VARS=%__ENVY_VARS%{v.Key} \"\n");
            s.Append($":envy_v{label}\n");
            s.Append(line).Append('\n');
        }
        return s.ToString();
    }

    /// <summary>
    /// The set command for <paramref name="v"/>, or null when cmd can't hold the value. Literal values are caret-escaped
    /// rather than quoted, so quotes inside them can't end the string; expanding values are quoted so the variables they
    /// refer to may contain special characters.
    /// </summary>
    internal static string? SetLine(EnvVar v)
    {
        if (v.Value.Contains('\n') || v.Value.Contains('\r')) return null;
        string line;
        if (!v.Expands)
        {
            var b = new StringBuilder($"@set {v.Key}=");
            foreach (var c in v.Value)
            {
                if (c is '^' or '&' or '|' or '<' or '>' or '"') b.Append('^');
                b.Append(c == '%' ? "%%" : c.ToString());
            }
            line = b.ToString();
        }
        else
        {
            var b = new StringBuilder($"@set \"{v.Key}=");
            foreach (var token in Expansion.Parse(v.Value))
            {
                switch (token)
                {
                    case Expansion.Literal l when l.Text.Contains('"'): return null;
                    case Expansion.Literal l: b.Append(l.Text.Replace("%", "%%")); break;
                    case Expansion.Home: b.Append("%USERPROFILE%"); break;
                    case Expansion.Reference r: b.Append('%').Append(r.Name).Append('%'); break;
                }
            }
            line = b.Append('"').ToString();
        }
        return line.Length > 8000 ? null : line;
    }

    /// <summary>Text inside a quoted batch string: percent signs doubled.</summary>
    static string Escape(string s) => s.Replace("%", "%%");

    static string Comment(string s) => new(Scopes.CommentSafe(s).Select(c => c is '&' or '|' or '<' or '>' or '^' or '%' ? ' ' : c).ToArray());
}
